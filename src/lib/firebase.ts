// Anonymous Browser Identifier for Ratings
export function getAnonymousIdentifier(): string {
  let id = localStorage.getItem('cv_anon_id');
  if (!id) {
    id = 'anon_' + Math.random().toString(36).substring(2, 15) + Math.random().toString(36).substring(2, 15);
    localStorage.setItem('cv_anon_id', id);
  }
  return id;
}
